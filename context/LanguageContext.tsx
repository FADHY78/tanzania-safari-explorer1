interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  currentLanguageInfo: LanguageInfo;
  t: (key: string) => string;
  supportedLanguages: LanguageInfo[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const STORAGE_KEY = 'embuat_safaris_lang';

// Helper to trigger Google Translate on the entire DOM
const triggerGoogleTranslate = (code: LanguageCode) => {
  if (typeof window === 'undefined') return;
  try {
    const isEn = code === 'en';
    const cookieVal = isEn ? '/en/en' : `/en/${code}`;
    const expires = new Date(Date.now() + 30 * 86400000).toUTCString();

    // Set translation cookies
    document.cookie = `googtrans=${cookieVal}; expires=${expires}; path=/;`;
    if (isEn) {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;`;
    }
    if (window.location.hostname) {
      document.cookie = `googtrans=${cookieVal}; expires=${expires}; path=/; domain=${window.location.hostname};`;
      document.cookie = `googtrans=${cookieVal}; expires=${expires}; path=/; domain=.${window.location.hostname};`;
      if (isEn) {
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; domain=${window.location.hostname};`;
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; domain=.${window.location.hostname};`;
      }
    }

    const fireChange = (sel: HTMLSelectElement) => {
      sel.value = isEn ? '' : code;
      sel.dispatchEvent(new Event('change', { bubbles: true }));
      sel.dispatchEvent(new Event('input', { bubbles: true }));
    };

    const select = document.querySelector('select.goog-te-combo') as HTMLSelectElement | null;
    if (select) {
      fireChange(select);
    } else {
      let attempts = 0;
      const interval = setInterval(() => {
        attempts++;
        const retry = document.querySelector('select.goog-te-combo') as HTMLSelectElement | null;
        if (retry) {
          fireChange(retry);
          clearInterval(interval);
        } else if (attempts > 25) {
          clearInterval(interval);
        }
      }, 200);
    }
  } catch {
    // Ignore translation errors
  }
};

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && ['en', 'fr', 'de', 'it', 'es', 'sw'].includes(saved)) {
        return saved as LanguageCode;
      }
    } catch {
      // Ignore
    }
    return 'en';
  });

  const setLanguage = (code: LanguageCode) => {
    if (code === language) return;
    setLanguageState(code);
    try {
      localStorage.setItem(STORAGE_KEY, code);
      document.documentElement.lang = code;
    } catch {
      // Ignore
    }
    triggerGoogleTranslate(code);

    // Fast seamless reload guarantees 100% full-site translation across all 84 tours and dynamic itineraries
    setTimeout(() => {
      window.location.reload();
    }, 120);
  };

  useEffect(() => {
    try {
      document.documentElement.lang = language;
    } catch {
      // Ignore
    }
    // If not English on initial mount, trigger Google Translate
    if (language !== 'en') {
      triggerGoogleTranslate(language);
    }
  }, [language]);

  const currentLanguageInfo = SUPPORTED_LANGUAGES.find(l => l.code === language) || SUPPORTED_LANGUAGES[0];

  const t = (key: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return TRANSLATIONS.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      currentLanguageInfo,
      t,
      supportedLanguages: SUPPORTED_LANGUAGES
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export default LanguageContext;
